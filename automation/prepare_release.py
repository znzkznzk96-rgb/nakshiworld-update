"""One release history generates both in-game mail and GitHub release notes."""
import json, pathlib, sys
repo = pathlib.Path(__file__).resolve().parents[1]
history = json.loads((repo/'automation/release-history.json').read_text())
version = json.loads((repo/'automation/release.json').read_text())
assert len({n['id'] for n in history}) == len(history), 'Duplicate mail ID'
assert history[0]['id'] == version['name'], 'Add current release notes before publishing'
for n in history:
    assert n['title'] and n['summary'] and 0 < len(n['body']) <= 10
    assert all(isinstance(line,str) and line for line in n['body'])
source = 'extends RefCounted\n# Generated by automation/prepare_release.py; edit release-history.json.\nconst LETTERS = '+json.dumps(history,ensure_ascii=False,indent=2)+'\n'
(repo/'game/addons/reservoir/release_notes.gd').write_text(source)
if len(sys.argv)>1:
    pathlib.Path(sys.argv[1]).write_text('\n'.join('- '+line for line in history[0]['body'])+'\n')
